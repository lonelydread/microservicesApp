CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL,
    product_id UUID NOT NULL,
    quantity INTEGER NOT NULL,
    price NUMERIC(19, 2) NOT NULL,
    sale NUMERIC(5, 2) NOT NULL,
    total_price NUMERIC(29, 2) NOT NULL,
    user_id UUID NOT NULL,
    CONSTRAINT uk_orders_order_product UNIQUE (order_id, product_id),
    CONSTRAINT chk_orders_quantity CHECK (quantity > 0),
    CONSTRAINT chk_orders_price CHECK (price > 0),
    CONSTRAINT chk_orders_sale CHECK (sale >= 0 AND sale <= 100),
    CONSTRAINT chk_orders_total_price CHECK (total_price >= 0)
);

